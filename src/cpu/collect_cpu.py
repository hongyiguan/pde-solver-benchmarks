"""
Collect data generated by run_cpu.sh 
example: python collect_cpu.py /path/to/out_file --out_csv /path/to/out_csv 
"""

import os
import argparse
import csv

def parse_file(path):
    rows = []
    with open(path, "r", encoding="utf-8", errors="ignore") as f:
        lines = f.readlines()

    source = os.path.basename(path)
    current_params = {}

    for line in lines:
        line = line.strip()
        if line.startswith("Problem size:"):
            parts = line.replace(",", "").split()
            for p in parts:
                if p.startswith("N="):
                    current_params["N"] = int(p.split("=")[1])
                elif p.startswith("innerSquare="):
                    current_params["inner"] = int(p.split("=")[1])
                elif p.startswith("alpha="):
                    current_params["alpha"] = float(p.split("=")[1])
        elif line.startswith("BiCGSTAB solve time:"):
            t = float(line.split(":")[1].split()[0])
            rows.append([source, "BiCGSTAB+ILU", current_params.get("N"), current_params.get("inner"), current_params.get("alpha"), t])
        elif line.startswith("ADI solve time:"):
            t = float(line.split(":")[1].split()[0])
            rows.append([source, "ADI", current_params.get("N"), current_params.get("inner"), current_params.get("alpha"), t])
        elif line.startswith("Relative L2:"):
            val = float(line.split(":")[1])
            rows[-1].append(val)

    return rows

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("path", help="Directory or single file")
    ap.add_argument("--out_csv", default="command48_results.csv")
    args = ap.parse_args()

    targets = []
    if os.path.isdir(args.path):
        for root, _, files in os.walk(args.path):
            for name in files:
                targets.append(os.path.join(root, name))
    else:
        targets = [args.path]

    rows = []
    for fp in targets:
        rows.extend(parse_file(fp))

    if not rows:
        print("No records parsed.")
        return

    with open(args.out_csv, "w", newline="") as g:
        w = csv.writer(g)
        w.writerow(["source","solver","N","inner","alpha","time(s)","L2-diff"])
        w.writerows(rows)
    print(f"Wrote {args.out_csv} with {len(rows)} rows")

if __name__ == "__main__":
    main()

