"""
Collect data generated by run_gpu.sh 
example: python collect_gpu.py /path/to/out_file --out_csv /path/to/out_csv 
"""

import os
import argparse
import csv

def parse_header(line):
    line = line.strip()
    if line.startswith("ILU(0) |"):
        solver = "ILU(0)"
    elif line.startswith("GMRES + AMG |"):
        solver = "GMRES+AMG"
    else:
        return None

    parts = line.split("|", 1)[1].strip().split()
    vals = {kv.split("=")[0]: kv.split("=")[1] for kv in parts}
    N = int(vals["N"])
    inner = int(vals["inner"])
    alpha = float(vals["alpha"])
    return solver, N, inner, alpha

def parse_avg_time(line):
    s = line.strip()
    if not s.startswith(">> Average time over"):
        return None
    try:
        val = s.split(":")[1].strip().split()[0]
        return float(val)
    except Exception:
        return None

def scan_file(path, rows):
    with open(path, "r", encoding="utf-8", errors="ignore") as f:
        pending = None  
        for line in f:
            if pending is None:
                hdr = parse_header(line)
                if hdr:
                    pending = hdr
            else:
                t = parse_avg_time(line)
                if t is not None:
                    solver, N, inner, alpha = pending
                    rows.append([os.path.basename(path), solver, N, inner, alpha, t])
                    pending = None

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("path", help="A directory OR a single log file")
    ap.add_argument("--out_csv", default="gpu_results.csv")
    args = ap.parse_args()

    targets = []
    if os.path.isdir(args.path):
        for root, _, files in os.walk(args.path):
            for name in files:
                targets.append(os.path.join(root, name))
    else:
        targets = [args.path]

    rows = []
    for fp in targets:
        try:
            scan_file(fp, rows)
        except Exception:
            pass

    if not rows:
        print("No GPU records parsed.")
        return

    os.makedirs(os.path.dirname(args.out_csv) or ".", exist_ok=True)
    with open(args.out_csv, "w", newline="") as g:
        w = csv.writer(g)
        w.writerow(["source","solver","N","inner","alpha","avg_time_s"])
        w.writerows(rows)
    print(f"Wrote {args.out_csv} ({len(rows)} rows)")

if __name__ == "__main__":
    main()

